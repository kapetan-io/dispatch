// SummaryLine is one line of a check's account of what dispatch tracks.
type SummaryLine struct {
	Name string
	Text string
}

// Summary describes how many records of each kind the state holds and what scope they came from.
func (s *State) Summary(statuses config.Statuses) []SummaryLine {
	count := func(kind string) int {
		n := 0
		for _, r := range s.kinds[kind] {
			if !r.hidden {
				n++
			}
		}
		return n
	}
	cfg := s.Config.Plugins.Linear
	scope := fmt.Sprintf("teams %s; statuses %s", strings.Join(cfg.Teams, ", "),
		strings.Join([]string{statuses.Todo, statuses.InProgress, statuses.InReview, statuses.NeedsHuman}, ", "))
	if s.Viewer != "" {
		scope = "assigned to " + s.Viewer + "; " + scope
	}
	workers, running := 0, 0
	for _, r := range s.kinds["worker"] {
		if r.hidden {
			continue
		}
		workers++
		if r.v.Interface().(*Worker).State.Value != "none" {
			running++
		}
	}
	return []SummaryLine{
		{"ticket", fmt.Sprintf("%d tracked tickets (%s)", count("ticket"), scope)},
		{"pr", fmt.Sprintf("%d open PRs read (In Review tickets whose worker is idle or gone)", count("pr"))},
		{"worker", fmt.Sprintf("%d workers, %d running", workers, running)},
		{"tree", fmt.Sprintf("%d trees in %d pools", count("tree"), len(s.Config.Repos))},
		{"escalation", fmt.Sprintf("%d escalations in the ledger", count("escalation"))},
	}
}
