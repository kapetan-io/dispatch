// ticketMethods are the methods a ticket record has beyond its facts.
const ticketMethods = "  hasLabel(name: string): boolean;\n"

// helperTypes are the plain value types records hold, named in the order they are declared.
var helperTypes = []reflect.Type{
	reflect.TypeFor[Seen](), reflect.TypeFor[Label](), reflect.TypeFor[Stop](), reflect.TypeFor[Command](), reflect.TypeFor[Turn](), reflect.TypeFor[Blocker](),
}

// typeDocs are the descriptions of the helper types that have one.
var typeDocs = map[reflect.Type]string{
	reflect.TypeFor[Command](): "A slash command the worker's current Claude session took.",
	reflect.TypeFor[Turn]():    "A turn the worker's current Claude session ended.",
}

// Declarations returns the contents of dispatch.d.ts. rules is the user's
// [rules] table, whose keys become typed members of ctx.config.rules.
func Declarations(rules config.Rules) string {
	var b strings.Builder
	b.WriteString("// Generated by `dispatch rules check` from dispatch's Go types. Do not edit.\n")
	b.WriteString("declare module \"dispatch\" {\n")
	for _, t := range helperTypes {
		if doc, ok := typeDocs[t]; ok {
			fmt.Fprintf(&b, "  /** %s */\n", doc)
		}
		fmt.Fprintf(&b, "  export interface %s {\n%s  }\n", t.Name(), indentFields(structFields(t, false), "    "))
	}
	for _, k := range Kinds {
		fmt.Fprintf(&b, "  export interface %s {\n%s", k.TS, indentFields(structFields(k.Type, true), "    "))
		if k.Name == "ticket" {
			b.WriteString("  " + ticketMethods)
		}
		b.WriteString("  }\n")
	}
	for _, e := range Events {
		fmt.Fprintf(&b, "  export interface %s {\n%s  }\n", e.TS, indentFields(structFields(e.Type, false), "    "))
	}
	b.WriteString("  export type RecordKind = " + joinQuoted(kindNames()) + ";\n")
	b.WriteString("  export interface RecordMap {\n")
	for _, k := range Kinds {
		fmt.Fprintf(&b, "    %q: %s;\n", k.Name, k.TS)
	}
	b.WriteString("  }\n  export type RecordOf<K extends RecordKind> = RecordMap[K];\n")
	b.WriteString("  export interface EventMap {\n")
	for _, e := range Events {
		fmt.Fprintf(&b, "    %q: %s;\n", e.Name, e.TS)
	}
	b.WriteString("  }\n  export type EventType = keyof EventMap;\n  export type EventOf<E extends EventType> = EventMap[E];\n")
	b.WriteString(configDeclaration(rules))
	b.WriteString(staticDeclarations)
	b.WriteString("  export interface Ctx {\n")
	b.WriteString("    now: number;\n    every(period: number, since: number): number;\n    config: Config;\n")
	b.WriteString("    ledger: {\n      receipts(subject: Ticket | PR | Tree | Worker, filter?: { kind?: string | string[]; topic?: string }): Receipt[];\n      done(subject: Ticket | PR | Tree | Worker, once: Once): boolean;\n    };\n")
	b.WriteString(ctxPlugins())
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return b.String()
}

const staticDeclarations = `  export type Once = [topic: string, ...values: (string | number | boolean | undefined)[]];
  export interface Receipt {
    kind: string;
    once: Once;
    rule: string;
    outcome?: "done" | "refused" | "failed";
    detail: string;
    started: number;
    ended?: number;
    reset?: boolean;
  }
  export interface HttpResponse { status: number; body: unknown }
  export interface Action { readonly queued: true }
  export function whenever<K extends RecordKind>(rule: {
    name: string;
    each: K;
    if: (record: RecordOf<K>, ctx: Ctx) => boolean;
    then: (record: RecordOf<K>, ctx: Ctx) => Action | Action[] | void;
    shadow?: boolean;
  }): void;
  export function on<E extends EventType>(rule: {
    name: string;
    event: E;
    if: (event: EventOf<E>, ctx: Ctx) => boolean;
    then: (event: EventOf<E>, ctx: Ctx) => Action | Action[] | void;
    shadow?: boolean;
  }): void;
  export function known(read: () => unknown): boolean;
  export function minutes(n: number): number;
  export function hours(n: number): number;
`

// ctxPlugins declares each plugin's reads and the actions it lets a rule queue.
func ctxPlugins() string {
	reads := map[string]string{
		"ticket": `      parent(t: Ticket): Ticket | undefined;
      children(t: Ticket): Ticket[];
      blockers(t: Ticket): Blocker[];
      blockersRead(t: Ticket): Blocker[];
      waitingSince(t: Ticket): number;
`,
		"worker": `      of(t: Ticket): Worker;
      in(tree: Tree): Worker;
`,
		"tree": `      pool(repo: string | undefined): { returns: number };
      leased(t: Ticket): boolean;
`,
		"pr":     "",
		"notify": "",
		"http": `      get(service: string, path: string): HttpResponse;
      last(service: string, path: string): HttpResponse;
`,
	}
	var b strings.Builder
	for _, plugin := range []string{"ticket", "worker", "tree", "pr", "notify", "http"} {
		fmt.Fprintf(&b, "    %s: {\n%s", plugin, reads[plugin])
		for _, a := range Actions {
			if a.Plugin != plugin {
				continue
			}
			params := []string{a.Subject.Name + ": " + a.Subject.TS}
			for _, p := range a.Params {
				params = append(params, p.Name+": "+p.TS)
			}
			opts := "once: Once"
			if a.Options != "" {
				opts += "; " + a.Options
			}
			params = append(params, "o: { "+opts+" }")
			fmt.Fprintf(&b, "      %s(%s): Action;\n", a.Method, strings.Join(params, ", "))
		}
		b.WriteString("    };\n")
	}
	return b.String()
}

func kindNames() []string {
	names := make([]string, len(Kinds))
	for i, k := range Kinds {
		names[i] = k.Name
	}
	return names
}

func joinQuoted(names []string) string {
	q := make([]string, len(names))
	for i, n := range names {
		q[i] = fmt.Sprintf("%q", n)
	}
	return strings.Join(q, " | ")
}

// field is one property of a declared interface.
type field struct {
	name     string
	ts       string
	optional bool
	readonly bool
	doc      string
}

func indentFields(fields []field, indent string) string {
	var b strings.Builder
	for _, f := range fields {
		q := ""
		if f.optional {
			q = "?"
		}
		ro := ""
		if f.readonly {
			ro = "readonly "
		}
		if f.doc != "" {
			fmt.Fprintf(&b, "%s/** %s */\n", indent, f.doc)
		}
		fmt.Fprintf(&b, "%s%s%s%s: %s;\n", indent, ro, f.name, q, f.ts)
	}
	return b.String()
}

// structFields lists the declared properties of a record or payload struct.
// facts is true for a record, whose fields are Fact values.
func structFields(t reflect.Type, facts bool) []field {
	var out []field
	for i := range t.NumField() {
		sf := t.Field(i)
		name, opts, _ := strings.Cut(sf.Tag.Get("js"), ",")
		if name == "" {
			continue
		}
		ft := sf.Type
		if facts {
			ft = ft.Field(0).Type
		}
		ts := sf.Tag.Get("ts")
		if ts == "" {
			ts = tsType(ft, sf.Tag.Get("ref"))
		}
		out = append(out, field{name: name, ts: ts, optional: opts == "optional", readonly: facts, doc: sf.Tag.Get("doc")})
	}
	return out
}

func tsType(t reflect.Type, ref string) string {
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int64, reflect.Float64:
		return "number"
	case reflect.Slice:
		return tsType(t.Elem(), ref) + "[]"
	case reflect.Pointer:
		return tsType(t.Elem(), ref) + " | undefined"
	case reflect.Struct:
		if t == reflect.TypeFor[Ref]() {
			return refTS(ref)
		}
		return t.Name()
	}
	return "unknown"
}

// configDeclaration declares ctx.config from the config structs, with the keys
// of the user's [rules] table typed by the values the file gives them.
func configDeclaration(rules config.Rules) string {
	var b strings.Builder
	b.WriteString("  export interface Config {\n")
	for _, f := range configFields(reflect.TypeFor[config.Config](), rules) {
		fmt.Fprintf(&b, "    %s: %s;\n", f.name, f.ts)
	}
	b.WriteString("    hasRepo(label: string | undefined): boolean;\n  }\n")
	return b.String()
}

func configFields(t reflect.Type, rules config.Rules) []field {
	var out []field
	for i := range t.NumField() {
		sf := t.Field(i)
		name, _, _ := strings.Cut(sf.Tag.Get("toml"), ",")
		if name == "" || sf.Tag.Get("ctx") == "-" {
			continue
		}
		out = append(out, field{name: name, ts: configType(sf.Type, name, rules)})
	}
	return out
}

func configType(t reflect.Type, name string, rules config.Rules) string {
	if t == reflect.TypeFor[config.Duration]() {
		return "string"
	}
	if t == reflect.TypeFor[config.Rules]() {
		keys := make([]string, 0, len(rules))
		for key := range rules {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		var parts []string
		for _, key := range keys {
			parts = append(parts, fmt.Sprintf("%q: %s", key, valueType(rules[key])))
		}
		return "{ " + strings.Join(append(parts, "[key: string]: unknown"), "; ") + " }"
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int64:
		return "number"
	case reflect.Slice:
		return configType(t.Elem(), name, rules) + "[]"
	case reflect.Map:
		return "{ [label: string]: " + configType(t.Elem(), name, rules) + " }"
	case reflect.Struct:
		var parts []string
		for _, f := range configFields(t, rules) {
			parts = append(parts, f.name+": "+f.ts)
		}
		return "{ " + strings.Join(parts, "; ") + " }"
	}
	return "unknown"
}

// valueType is the TypeScript type of a value read from the [rules] table.
func valueType(v any) string {
	switch v := v.(type) {
	case string:
		return "string"
	case bool:
		return "boolean"
	case int64, float64:
		return "number"
	case []any:
		if len(v) == 0 {
			return "unknown[]"
		}
		kinds := map[string]bool{}
		for _, item := range v {
			kinds[valueType(item)] = true
		}
		names := make([]string, 0, len(kinds))
		for k := range kinds {
			names = append(names, k)
		}
		slices.Sort(names)
		return "(" + strings.Join(names, " | ") + ")[]"
	case map[string]any:
		keys := make([]string, 0, len(v))
		for key := range v {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		var parts []string
		for _, key := range keys {
			parts = append(parts, fmt.Sprintf("%q: %s", key, valueType(v[key])))
		}
		return "{ " + strings.Join(parts, "; ") + " }"
	}
	return "unknown"
}
